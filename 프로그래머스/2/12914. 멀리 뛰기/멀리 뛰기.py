def solution(n):
    
    
    # 1 or 2칸 뛸 수 있음
    
    # n = 1 -> 1 총 1
    # n = 2 -> 1,1 / 2 총 2
    # n = 3 -> 1,1,1 / 1,2/ 2,1  총 3
    # n = 4 -> 1,1,1,1 / 1,1,2 / 2,1,1/ 1,2,1/ 2,2 총 5
    a = [1,1]
    
    for i in range(2,n+1):
        a.append(a[i-1]+a[i-2])
    
    
    
    return a[n]%1234567